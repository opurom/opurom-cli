import fs from 'node:fs';
import path from 'node:path';
import { CLI_ROOT } from './paths.mjs';
import { TARGETS } from './targets.mjs';

export function init(dir, { cwd = process.cwd() } = {}) {
  const target = path.resolve(cwd, String(dir));
  if (fs.existsSync(target)) {
    if (!fs.statSync(target).isDirectory()) throw new Error(`not a directory: ${target}`);
    if (fs.readdirSync(target).length > 0) {
      throw new Error(`refusing to overwrite non-empty directory: ${target}`);
    }
  }

  const name = path.basename(target);
  fs.mkdirSync(path.join(target, 'src'), { recursive: true });
  fs.writeFileSync(
    path.join(target, 'opurom.json'),
    `${JSON.stringify({ name, targets: [...TARGETS] }, null, 2)}\n`,
  );
  fs.copyFileSync(path.join(CLI_ROOT, 'templates', 'main.opu'), path.join(target, 'src', 'main.opu'));
  fs.writeFileSync(
    path.join(target, 'README.md'),
    `# ${name}\n\nGenerated by \`opurom init\`. Edit [src/main.opu](src/main.opu), then:\n\n` +
      '```sh\n' +
      'node <path-to>/opurom-cli/bin/opurom.mjs check src/main.opu\n' +
      'node <path-to>/opurom-cli/bin/opurom.mjs build --src src/main.opu --target web --out dist/web\n' +
      'node <path-to>/opurom-cli/bin/opurom.mjs dev --src src/main.opu\n' +
      '```\n',
  );
  fs.writeFileSync(path.join(target, '.gitignore'), 'node_modules/\n.DS_Store\ndist/\ntmp/\n');
  return target;
}
